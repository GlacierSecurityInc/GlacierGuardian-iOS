    static func mask(_ text: String) -> String {
        var maskedText = text
        let lowercasedText = text.lowercased()
        for word in bannedWords {
            let pattern = "\\b" + NSRegularExpression.escapedPattern(for: word) + "\\b"
            guard let regex = try? NSRegularExpression(pattern: pattern, options: []) else { continue }
            let matches = regex.matches(in: lowercasedText, options: [], range: NSRange(lowercasedText.startIndex..., in: lowercasedText))
            for match in matches.reversed() {
                guard let lowerRange = Range(match.range, in: lowercasedText) else { continue }
                let start = lowercasedText.distance(from: lowercasedText.startIndex, to: lowerRange.lowerBound)
                let end = lowercasedText.distance(from: lowercasedText.startIndex, to: lowerRange.upperBound)
                let startIndex = maskedText.index(maskedText.startIndex, offsetBy: start)
                let endIndex = maskedText.index(maskedText.startIndex, offsetBy: end)
                let range = startIndex..<endIndex
                let found = String(maskedText[range])
                if let first = found.first {
                    let replacement = String(first) + String(repeating: "*", count: max(found.count - 1, 0))
                    maskedText.replaceSubrange(range, with: replacement)
                }
            }
        }
        return maskedText
    }
